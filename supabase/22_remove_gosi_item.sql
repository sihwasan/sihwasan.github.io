-- =====================================================================
--  22. 자료실에서 고시가이드 항목 삭제
--
--  고시가이드북은 노회가 판매하는 자료이므로 자료실에 올리지 않습니다.
--  안내 항목까지 지웁니다.
--
--  * 짧습니다. 그대로 붙여넣어 실행해 주세요.
--  * 여러 번 실행해도 안전합니다.
-- =====================================================================

delete from public.archive_items
 where title like '시화산노회 고시부 목사장로 고시가이드%';


-- 확인 : 고시 분류에 남은 자료가 없어야 정상입니다.
select coalesce(count(*), 0) as "고시 분류에 남은 자료"
  from public.archive_items
 where section = '고시';
