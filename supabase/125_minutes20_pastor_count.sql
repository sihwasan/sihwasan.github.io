-- =====================================================================
--  125. 제20회 정기노회 회의록 — 목사회원 재적 55명 → 54명 (총회원 84명) (2026-10-20)
--
--  회의록 게시판(minutes_board)의 「제20회기 가을 정기노회 회의록」 본문에서
--  「목사회원 55명」을 「목사회원 54명」으로 고친다 (목사 54 + 장로총대 25 + 목사언권회원 5 = 총회원 84).
--  혹시 「총회원 85명」으로 적힌 곳이 있으면 「총회원 84명」으로 함께 고친다.
--  다른 글자는 건드리지 않는다.
--
--  실행: Supabase → SQL Editor → 전체 붙여넣고 Run.  여러 번 실행해도 안전합니다.
-- =====================================================================

update public.minutes_board
   set body = replace(replace(body, '목사회원 55명', '목사회원 54명'), '총회원 85명', '총회원 84명')
 where title like '%제20회%'
   and (body like '%목사회원 55명%' or body like '%총회원 85명%');

-- 확인: 「목사회원 54명 중 34명 … 총회원 84명 중 46명」으로 보이면 끝
select id, title,
       substring(body from greatest(position('서기 권병렬' in body), 1) for 140) as "회원호명 부분"
  from public.minutes_board
 where title like '%제20회%';
