-- =====================================================================
--  38. 미래교회자립위원회 위원장
--
--  미래교회자립위원회의 위원장은 <직전 노회장>이 맡습니다.
--  제19회기 현재 직전 노회장은 박양수 목사입니다.
--
--  (노회규칙 제4장에 따라 직전 노회장은 사회복지부 부장도 함께 맡으므로,
--   사회복지부 부장과 같은 분으로 나오는 것이 맞습니다.)
--
--  회기가 바뀌어 노회장이 바뀌면 이 자리도 함께 바뀝니다.
--  그때는 SQL 을 다시 돌리실 필요 없이
--    관리자 → 회원 관리 → 상비부 배정 관리
--  에서 위원장 이름만 고쳐 주시면 됩니다.
--
--  실행 방법
--    Supabase 대시보드 → SQL Editor → New query →
--    이 파일 전체를 붙여넣고 Run 클릭
--
--  ※ 37_boards_and_audit_window.sql 을 먼저 실행하셔야 합니다.
--  ※ 여러 번 실행해도 안전합니다.
--     (이미 다른 분으로 채워 두셨다면 그대로 둡니다)
-- =====================================================================

update public.committees
   set head = '박양수 목사',
       duty = '미자립교회 지원과 관련한 제반 정책 및 시행 사항을 담당하며, 지원 신청 청원을 심의한다. '
              '위원장은 직전 노회장이 맡는다. 세부 사항은 미래교회자립위원회 내규를 따른다.',
       updated_at = now()
 where name = '미래교회자립위원회'
   and coalesce(btrim(head), '') = '';


-- ---------------------------------------------------------------------
-- 확인
-- ---------------------------------------------------------------------
select name as "상비부", coalesce(head, '-') as "부장·위원장",
       coalesce(clerk, '-') as "서기", coalesce(treasurer, '-') as "회계", sort as "순서"
  from public.committees
 order by sort;
