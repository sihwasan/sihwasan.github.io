-- 52. 성경 과목 추가
--   · 고시가이드에 따라 성경은 장로·전도사·목사후보생 과목이다.
--   · 성경은 성경통신 신구약 수료증으로 대체할 수 있으므로,
--     모의고사에서 "성경 제외하기"를 고를 수 있게 start_exam 에 제외 목록을 받는다.
--   · 문제는 「시화산노회 고시부 목사장로 고시가이드」 성경 과목에서 그대로 옮겼다.

create or replace function public.exam_subjects(p_track text)
returns text[] language sql immutable as $fn$
  select case p_track
    when '목사'       then array['목회학', '권징조례', '신조', '예배모범']
    when '장로'       then array['성경', '정치', '권징조례', '신조', '상식', '소요리']
    when '전도사'     then array['성경', '상식', '영어']
    when '목사후보생' then array['성경', '상식', '영어']
    else array[]::text[]
  end;
$fn$;

-- 제외 과목을 받는 start_exam (기존 2인자 판은 그대로 두고 새 판을 얹는다)
create or replace function public.start_exam(p_track text, p_per_subject integer, p_exclude text[])
returns table (attempt_id bigint, qid bigint, subject text, question text, options jsonb)
language plpgsql security definer set search_path = public as $fn$
declare
  v_uid    uuid := auth.uid();
  v_name   text;
  v_subs   text[];
  v_ids    bigint[];
  v_att    bigint;
  v_n      integer := greatest(1, least(coalesce(p_per_subject, 10), 30));
begin
  if v_uid is null then
    raise exception '로그인이 필요합니다.';
  end if;

  select p.name into v_name from public.profiles p where p.id = v_uid;

  -- 보던 시험을 끝내지 않고 나갔다면 그 시험을 이어서 본다
  select a.id, a.question_ids into v_att, v_ids
    from public.exam_attempts a
   where a.user_id = v_uid and a.submitted_at is null
   order by a.started_at desc limit 1;
  if v_att is not null then
    return query
      select v_att, q.id, q.subject, q.question, q.options
        from public.exam_questions q
        join unnest(v_ids) with ordinality u(id, ord) on u.id = q.id
       order by u.ord;
    return;
  end if;

  v_subs := public.exam_subjects(p_track);
  if p_exclude is not null then
    select coalesce(array_agg(s), array[]::text[]) into v_subs
      from unnest(v_subs) s where not (s = any(p_exclude));
  end if;

  select coalesce(array_agg(id order by subject, rn), array[]::bigint[]) into v_ids
    from (select q.id, q.subject,
                 row_number() over (partition by q.subject order by random()) as rn
            from public.exam_questions q
           where q.active and q.subject = any(v_subs)) t
   where t.rn <= v_n;

  if coalesce(array_length(v_ids, 1), 0) = 0 then
    raise exception '출제할 문제가 없습니다.';
  end if;

  insert into public.exam_attempts (user_id, user_name, track, question_ids, total)
  values (v_uid, coalesce(v_name, ''), p_track, v_ids, array_length(v_ids, 1))
  returning id into v_att;

  return query
    select v_att, q.id, q.subject, q.question, q.options
      from public.exam_questions q
      join unnest(v_ids) with ordinality u(id, ord) on u.id = q.id
     order by u.ord;
end;
$fn$;

revoke all on function public.start_exam(text, integer, text[]) from public;
grant execute on function public.start_exam(text, integer, text[]) to authenticated;

