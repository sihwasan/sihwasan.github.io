--  116. 사회복지부 내규 6항 순서 바로잡기 (2026-10-20)
--
--  제20회 정기노회(2026. 10. 12.)에서 경조비 조항을 「내규 6-3)」으로 추가하기로 가결했는데,
--  홈페이지(rule_articles)에는 1)로 들어가 있어 순서를 바로잡는다.
--    1) 사회복지부장의 재량에 따라 한다.
--    2) 입원 시 3일 이상에 10만원을 지급한다.
--    3) 현 담임목사 및 부목사 등 정회원(또는 원로목사 은퇴목사)과 장로 총대 직계에 한하여 경조비를 … (신설)
--
--  실행: Supabase → SQL Editor → 전체 붙여넣고 Run.  여러 번 실행해도 안전합니다.
-- =====================================================================

update public.rule_articles
   set body = '1) 사회복지부장의 재량에 따라 한다.
2) 입원 시 3일 이상에 10만원을 지급한다.
3) 현 담임목사 및 부목사 등 정회원(또는 원로목사 은퇴목사)과 장로 총대 직계에 한하여 경조비를 지급할 수 있다. 단, 규정 미비에 따른 특수 상황은 부서 결의 (또는 사회복지부 임원회 협의)를 거쳐 처리할 수 있다.
개정 연혁: 2019. 4. 8. 개정 / 2022. 4. 18. 개정 / 2023. 10. 10. 개정 / 2026. 10. 12. 개정',
       updated_at = now(),
       updated_by = '116 sql (제20회 정기노회 결의 반영)'
 where book = 'presbytery' and doc_key = 'rule-bokji' and title like '6.%';

